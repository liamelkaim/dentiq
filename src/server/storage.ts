// Private file storage. Files are never served directly: every download goes through
// /api/files/[versionId], which checks permissions first.
//
// Local development stores files on disk in ./.data/uploads (ignored by git). To move to cloud
// object storage later (e.g. Cloudflare R2 or S3), implement FileStorage and return it from getStorage().
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { createBlobStorage } from "./blob-storage";

export interface FileStorage {
  put(key: string, data: Uint8Array): Promise<void>;
  get(key: string): Promise<Uint8Array | null>;
  getStream?(key: string): Promise<ReadableStream<Uint8Array> | null>;
  delete(key: string): Promise<void>;
}

// Keys are generated by Dentiq (e.g. "resources/<uuid>"), never taken from user input.
const KEY_PATTERN = /^[a-z0-9]+(\/[a-z0-9-]+)+$/;

export function assertValidKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new Error(`Invalid storage key: ${key}`);
}

export function createLocalStorage(root: string): FileStorage {
  const absoluteRoot = path.resolve(root);
  const resolve = (key: string) => {
    assertValidKey(key);
    const full = path.resolve(absoluteRoot, key);
    if (!full.startsWith(absoluteRoot + path.sep)) throw new Error(`Invalid storage key: ${key}`);
    return full;
  };

  return {
    async put(key, data) {
      const full = resolve(key);
      await mkdir(path.dirname(full), { recursive: true, mode: 0o700 });
      await writeFile(full, data, { mode: 0o600, flag: "wx" }); // never overwrite
    },
    async get(key) {
      try {
        return new Uint8Array(await readFile(resolve(key)));
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
        throw error;
      }
    },
    async delete(key) {
      await rm(resolve(key), { force: true });
    },
  };
}

export function createMemoryStorage(): FileStorage & { size(): number } {
  const files = new Map<string, Uint8Array>();
  return {
    async put(key, data) {
      assertValidKey(key);
      if (files.has(key)) throw new Error("exists");
      files.set(key, data);
    },
    async get(key) {
      assertValidKey(key);
      return files.get(key) ?? null;
    },
    async delete(key) {
      files.delete(key);
    },
    size: () => files.size,
  };
}

/** Cloud (Vercel Blob) storage is used only on Vercel or with an explicit opt-in. A token in a local .env file is ignored. */
export function cloudStorageEnabled(env: Record<string, string | undefined> = process.env): boolean {
  return env.VERCEL === "1" || env.DENTIQ_ENABLE_BLOB === "true";
}

const globalForStorage = globalThis as unknown as { dentosStorage?: FileStorage };

export function getStorage(): FileStorage {
  if (!globalForStorage.dentosStorage) {
    const token = process.env.BLOB_READ_WRITE_TOKEN;
    if (cloudStorageEnabled(process.env)) {
      if (!token) throw new Error("Private Blob storage must be configured when cloud storage is enabled");
      globalForStorage.dentosStorage = createBlobStorage(token);
    } else {
      globalForStorage.dentosStorage = createLocalStorage(process.env.UPLOADS_DIR || "./.data/uploads");
    }
  }
  return globalForStorage.dentosStorage;
}
